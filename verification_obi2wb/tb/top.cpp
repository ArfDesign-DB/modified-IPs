#include <verilated.h>
#include <verilated_vcd_c.h>

#include <queue>
#include <iostream>

#include "Vobi2wb.h"

#include "transaction.h"
#include "driver.h"
#include "monitor.h"
#include "scoreboard.h"
#include "wb_slave.h"
#include "test.h"

//==============================================================
// GLOBALS
//==============================================================

vluint64_t sim_time = 0;

// Mailbox : Monitor -> Scoreboard
std::queue<obi_transaction> mon2sb;

//==============================================================
// COMPONENTS
//==============================================================

driver      drv;

monitor     mon;

scoreboard  sb;

wb_slave    wb;

//==============================================================
// CLOCK TICK
//==============================================================

void tick(
    Vobi2wb* dut,
    VerilatedVcdC* tfp)
{
    //==========================================================
    // CLOCK LOW
    //==========================================================

    dut->clk_i = 0;

    // Slave always active
    wb.run(dut);

    dut->eval();

    tfp->dump(sim_time++);

    //==========================================================
    // CLOCK HIGH
    //==========================================================

    dut->clk_i = 1;

    // Slave always active
    wb.run(dut);

    dut->eval();

    tfp->dump(sim_time++);

    //==========================================================
    // FOREVER MONITOR
    //==========================================================

    mon.sample(dut);

    //==========================================================
    // FOREVER SCOREBOARD
    //==========================================================

    sb.check();
}

//==============================================================
// RESET
//==============================================================

void reset_dut(
    Vobi2wb* dut,
    VerilatedVcdC* tfp)
{
    std::cout
        << "\n==================================\n"
        << " RESET START\n"
        << "==================================\n";

    //==========================================================
    // RESET ASSERT
    //==========================================================

    dut->rst_ni = 0;

    // OBI
    dut->obi_req_i   = 0;

    dut->obi_addr_i  = 0;

    dut->obi_we_i    = 0;

    dut->obi_be_i    = 0;

    dut->obi_wdata_i = 0;

    // WB
    dut->wb_ack_i    = 0;

    dut->wb_dat_i    = 0;

    dut->wb_stall_i  = 0;

    //==========================================================
    // HOLD RESET
    //==========================================================

    for(int i=0; i<5; i++)
    {
        tick(dut, tfp);
    }

    //==========================================================
    // RESET RELEASE
    //==========================================================

    dut->rst_ni = 1;

    for(int i=0; i<5; i++)
    {
        tick(dut, tfp);
    }

    std::cout
        << "==================================\n"
        << " RESET DONE\n"
        << "==================================\n";
}

//==============================================================
// MAIN
//==============================================================

int main(int argc, char** argv)
{
    Verilated::commandArgs(argc, argv);

    //==========================================================
    // DUT
    //==========================================================

    Vobi2wb* dut = new Vobi2wb;

    //==========================================================
    // WAVES
    //==========================================================

    Verilated::traceEverOn(true);

    VerilatedVcdC* tfp =
        new VerilatedVcdC;

    dut->trace(tfp, 99);

    tfp->open("wave.vcd");

    //==========================================================
    // RESET
    //==========================================================

    reset_dut(dut, tfp);

    //==========================================================
    // START TESTING
    //==========================================================

    std::cout
        << "\n==================================\n"
        << " START TESTING\n"
        << "==================================\n";

    //==========================================================
    // TEST 1 : BASIC RW
    //==========================================================

    test_basic_rw(
        drv,
        dut,
        tfp);

    //==========================================================
    // TEST 2 : BACK TO BACK
    //==========================================================

    test_back_to_back(
        drv,
        dut,
        tfp);

    //==========================================================
    // TEST 3 : BYTE ENABLE
    //==========================================================

    test_byte_enable(
        drv,
        dut,
        tfp);

    //==========================================================
    // TEST 4 : RANDOM
    //==========================================================

    test_random(
        drv,
        dut,
        tfp);

    //==========================================================
    // FINAL REPORT
    //==========================================================

    sb.report();

    //==========================================================
    // END SIM
    //==========================================================

    std::cout
        << "\n==================================\n"
        << " SIMULATION DONE\n"
        << "==================================\n";

    //==========================================================
    // CLEANUP
    //==========================================================

    tfp->close();

    delete dut;

    delete tfp;

    return 0;
}
